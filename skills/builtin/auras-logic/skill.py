@tools.tool
def analyze_causality(statement: str) -> str:
    """Анализ причинно-следственных связей в утверждении.

    Args:
        statement: Утверждение (например «если А то Б»)
    """
    if not statement or len(statement) < 10:
        return "❌ Слишком короткое утверждение. Дай более развёрнутую мысль."

    markers = [
        ("потому что", "причина → следствие"),
        ("из-за", "причина → следствие"),
        ("поэтому", "причина → следствие"),
        ("следовательно", "причина → следствие"),
        ("в результате", "причина → следствие"),
        ("благодаря", "причина → следствие"),
        ("вследствие", "причина → следствие"),
        ("значит", "причина → следствие"),
        ("отсюда следует", "причина → следствие"),
    ]

    found = []
    for marker, pattern in markers:
        if marker in statement.lower():
            found.append(f"  🔗 «{marker}» — {pattern}")

    parts = [f"📝 Утверждение: «{statement}»"]

    if found:
        parts.append("Найденные связи:")
        parts.extend(found)
    else:
        parts.append("⚠️ Явных причинно-следственных маркеров не найдено.")

    parts.append("")
    parts.append("🧠 Логическая оценка:")
    parts.append("  • Определи где причина, а где следствие")
    parts.append("  • Проверь, нет ли скрытых факторов")
    parts.append("  • Может ли следствие существовать без причины?")

    return "\n".join(parts)


@tools.tool
def evaluate_argument(argument: str) -> str:
    """Оценка аргумента: сила, слабость, структура.

    Args:
        argument: Аргумент для оценки
    """
    if not argument or len(argument) < 15:
        return "❌ Дай более развёрнутый аргумент."

    has_because = any(
        m in argument.lower() for m in ["потому что", "так как", "поскольку"]
    )
    has_therefore = any(
        m in argument.lower() for m in ["поэтому", "следовательно", "значит"]
    )
    has_example = any(
        m in argument.lower() for m in ["например", "к примеру", "допустим"]
    )

    parts = [f"📝 Аргумент: «{argument}»", ""]
    parts.append("📊 Структура:")
    parts.append(f"  • Обоснование: {'✅ есть' if has_because else '❌ отсутствует'}")
    parts.append(f"  • Вывод: {'✅ есть' if has_therefore else '❌ отсутствует'}")
    parts.append(f"  • Примеры: {'✅ есть' if has_example else '⚠️ нет'}")

    score = sum([has_because, has_therefore, has_example, len(argument) > 50])

    parts.append("")
    parts.append("🎯 Сила аргумента:")
    if score >= 3:
        parts.append("  ✅ Структурированный, хорошо проработан")
    elif score >= 2:
        parts.append("  ⚠️ Средняя проработка, можно усилить примерами")
    else:
        parts.append("  ❌ Слабый — нужно больше обоснований и примеров")

    return "\n".join(parts)


@tools.tool
def logical_fallback_check(text: str) -> str:
    """Проверка текста на логические ошибки.

    Args:
        text: Текст для проверки
    """
    if not text or len(text) < 10:
        return "❌ Дай текст подлиннее для проверки."

    indicators = {
        "всегда": ("поспешное обобщение", "«Всегда» — признак обобщения"),
        "никогда": ("поспешное обобщение", "«Никогда» — признак обобщения"),
        "все знают": ("апелляция к большинству", "Апелляция к большинству"),
        "очевидно": ("круговая аргументация", "Очевидность — не аргумент"),
        "эксперты говорят": ("апелляция к авторитету", "Ссылка на неназванных экспертов"),
        "это же просто": ("апелляция к эмоциям", "Упрощение сложного вопроса"),
        "ты просто": ("ad hominem", "Переход на личности"),
        "если мы разрешим": ("скользкий склон", "Цепочка без обоснования"),
        "учёные доказали": ("апелляция к авторитету", "Неконкретная ссылка"),
        "любой дурак": ("ad hominem", "Оскорбление несогласных"),
    }

    found = []
    for phrase, (name, explanation) in indicators.items():
        if phrase.lower() in text.lower():
            found.append(f"  ⚠️ «{phrase}» → {name}: {explanation}")

    if not found:
        return "✅ Явных логических ошибок не обнаружено. Но всегда проверяй предпосылки!"

    return (
        "🔍 Найдены возможные логические ошибки:\n"
        + "\n".join(found)
        + "\n\n💡 Совет: проверь предпосылки и убедись что вывод следует из аргументов."
    )


