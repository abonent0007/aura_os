# idea-refine/skill.py
# Структурированное дивергентное→конвергентное мышление
from pathlib import Path
from datetime import datetime
from autogen.beta import tools

_IDEAS_DIR = Path(__file__).parent.parent.parent.parent / "docs" / "ideas"
_IDEAS_DIR.mkdir(parents=True, exist_ok=True)


@tools.tool
def start_ideation(topic: str) -> str:
    """
    Начать структурированный брейншторм.
    Проводит пользователя через три фазы:
    1. Дивергенция (расширение) — вопросы, варианты, грани
    2. Конвергенция (сужение) — оценка, стресс-тест, выбор
    3. One-pager — сохранение результата

    Вызывай когда пользователь говорит "помоги придумать", "нужна идея", "как лучше сделать".
    """
    return (
        f"💡 ИДЕЯ: {topic}\n"
        f"━━━━━━━━━━━━━━━━━━━━━━━\n\n"
        f"ФАЗА 1 — Дивергенция (расширим горизонты)\n"
        f"Ответь на вопросы (по одному):\n"
        f"1. Какую проблему решаем? Кому от этого станет лучше?\n"
        f"2. Какие есть варианты? Назови 3-5 разных подходов\n"
        f"3. А если бы ресурсов было бесконечно много? А если бы почти не было?\n"
        f"4. Кто уже делал похожее? Чем их опыт полезен?\n\n"
        f"ФАЗА 2 — Конвергенция (выберем лучшее)\n"
        f"После того как варианты собраны:\n"
        f"1. Стресс-тест: что может пойти не так с каждым вариантом?\n"
        f"2. Критерии: скорость, качество, стоимость, риски — что важнее?\n"
        f"3. Выбор: какой вариант побеждает и почему?\n\n"
        f"ФАЗА 3 — One-pager\n"
        f"Я сохраню результат в docs/ideas/ если ты попросишь.\n"
        f"Формат: проблема → решение → MVP → что НЕ делаем.\n\n"
        f"Начнём с Фазы 1. Какую проблему решаем?"
    )


@tools.tool
def stress_test_plan(plan: str) -> str:
    """
    Стресс-тест плана или идеи на прочность.
    Анализирует риски, слепые зоны и неочевидные последствия.
    """
    return (
        f"🔬 СТРЕСС-ТЕСТ ПЛАНА\n"
        f"━━━━━━━━━━━━━━━━━━━━\n\n"
        f"Проверяю на прочность:\n"
        f"«{plan[:300]}»{'…' if len(plan) > 300 else ''}\n\n"
        f"1. ДОПУЩЕНИЯ\n"
        f"   • Какие неявные допущения мы сделали?\n"
        f"   • Что должно быть правдой чтобы план сработал?\n"
        f"   • Какое допущение самое рискованное?\n\n"
        f"2. РИСКИ\n"
        f"   • Что может пойти не так на каждом шаге?\n"
        f"   • Что мы не учли? (люди, сроки, технологии)\n"
        f"   • Есть ли plan B?\n\n"
        f"3. ПОСЛЕДСТВИЯ\n"
        f"   • Если всё получится — какие побочные эффекты?\n"
        f"   • Кому может стать хуже от этого решения?\n"
        f"   • Что мы перестанем делать чтобы сделать это?\n\n"
        f"Ответь на каждый пункт кратко. Если рисков мало — план хорош."
    )


@tools.tool
def save_idea(name: str, content: str) -> str:
    """
    Сохранить проработанную идею в docs/ideas/.
    Вызывай после завершения брейншторма чтобы не потерять результат.
    """
    timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    safe_name = name.lower().replace(" ", "-").replace("/", "-")[:40]
    filename = f"{timestamp}_{safe_name}.md"
    filepath = _IDEAS_DIR / filename

    doc = (
        f"# {name}\n\n"
        f"**Создано:** {datetime.now().strftime('%Y-%m-%d %H:%M')}\n\n"
        f"---\n\n"
        f"{content}\n"
    )
    filepath.write_text(doc, encoding="utf-8")
    return f"💾 Идея сохранена: {filepath}"
