@tools.tool
def get_engineering_stats() -> str:
    """Статистика инженерных сессий: сколько багов исправлено, скиллов создано, тестов написано."""
    log = _load_log()
    sessions = log.get("sessions", [])
    completed = sum(1 for s in sessions if s.get("outcome"))
