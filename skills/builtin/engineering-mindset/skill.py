@tools.tool
def simplify_code(description: str) -> str:
    """
    Систематическое упрощение кода без изменения поведения.
    Используй когда код работает но читается тяжело, после ревью, или когда видишь накопленную сложность.

    Args:
        description: что упрощаем и почему
    """
    return (
        f"🔧 УПРОЩЕНИЕ КОДА: {description}\n"
        f"━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n"
        f"5 ПРИНЦИПОВ:\n\n"
        f"1. СОХРАНИ ПОВЕДЕНИЕ\n"
        f"   • Не меняй ЧТО делает код — только КАК\n"
        f"   • Все входы/выходы/ошибки/edge cases — идентичны\n"
        f"   • Не уверен что поведение сохранено? Не трогай\n"
        f"   • Все существующие тесты должны проходить\n\n"
        f"2. СЛЕДУЙ КОНВЕНЦИЯМ ПРОЕКТА\n"
        f"   • Изучи как соседний код решает похожие задачи\n"
        f"   • Импорты, функции, имена, ошибки — как в проекте\n"
        f"   • Упрощение ломающее консистентность — не упрощение\n\n"
        f"3. ЯСНОСТЬ ВЫШЕ ХИТРОСТИ\n"
        f"   • Явный код лучше компактного когда компактный требует паузы\n"
        f"   • Тернарные цепочки → if/else\n"
        f"   • Вложенные reduce → цикл с понятным именем переменной\n\n"
        f"4. УБЕРИ АБСТРАКЦИОННЫЙ НАЛОГ\n"
        f"   • Каждый слой абстракции должен окупаться\n"
        f"   • Не обобщай пока нет 3+ использований\n"
        f"   • Удали мёртвый код: _unused переменные, заглушки, /* removed */\n\n"
        f"5. УПРОСТИ ПОТОК ДАННЫХ\n"
        f"   • Данные должны течь в одном направлении\n"
        f"   • Убери ненужные промежуточные переменные\n"
        f"   • Группируй связанные данные в структуры\n\n"
        f"ЧЕКЛИСТ: перед/после — тесты проходят? Код читается быстрее? Новый член команды поймёт сходу?\n"
    )


