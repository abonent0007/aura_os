@tools.tool
def daily_horoscope(sign_or_date: str) -> str:
    """
    Гороскоп на сегодня по знаку зодиака или дате рождения.
    
    Args:
        sign_or_date: Знак зодиака (например, 'Водолей') или дата рождения ДД.ММ
    
    Returns:
        Текст гороскопа на сегодня.
    """
    # Пробуем распарсить как дату
    sign_name = sign_or_date.strip()
    try:
        if "." in sign_or_date:
            parts = sign_or_date.split(".")
            day, month = int(parts[0]), int(parts[1])
            sign_name, _, _ = _get_sign_by_date(day, month)
    except (ValueError, IndexError):
        pass

    # Ищем знак
    sign_name = sign_name.capitalize()
    valid_signs = [s[0] for s in SIGNS]
    if sign_name not in valid_signs:
        # Нечёткий поиск
        for s in valid_signs:
            if s.lower().startswith(sign_name.lower()[:3]):
                sign_name = s
                break
        else:
            return f"❌ Знак «{sign_or_date}» не распознан. Попробуй: Водолей, Овен, Телец..."

    templates = HOROSCOPE_TEMPLATES.get(sign_name, ["Сегодня обычный день, но ты можешь сделать его особенным."])
    horoscope = random.choice(templates)

    # Добавляем астро-контекст
    today = datetime.now()
    phase, lunar_day, phase_name, phase_desc = _moon_phase(today)
    _, sun_emoji, _ = _get_sign_by_date(today.day, today.month)
    sign_emoji = ""
    for s in SIGNS:
        if s[0] == sign_name:
            sign_emoji = s[1]
            break

    lines = []
    lines.append(f"🔮 Гороскоп на {today.strftime('%d.%m.%Y')} · {sign_emoji} {sign_name}")
    lines.append(f"   {phase_name} · лунный день {lunar_day}")
    lines.append("")
    lines.append(f"   {horoscope}")
    lines.append("")
    lines.append(f"   🌙 Лунный контекст: {phase_desc.lower()}")
    lines.append("")
    lines.append("⚠️ Развлекательный гороскоп. Не является профессиональным астрологическим прогнозом.")

    return "\n".join(lines)


