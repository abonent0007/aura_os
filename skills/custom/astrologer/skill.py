@tools.tool
def natal_chart(name: str, birth_date: str, birth_time: str = "12:00", birth_place: str = "Москва") -> str:
    """
    Построить натальную карту.
    
    Args:
        name: Имя человека
        birth_date: Дата рождения в формате ДД.ММ.ГГГГ
        birth_time: Время рождения в формате ЧЧ:ММ (по умолчанию 12:00)
        birth_place: Город рождения (по умолчанию Москва)
    
    Returns:
        Полная натальная карта с интерпретациями.
    """
    try:
        day, month, year = map(int, birth_date.split("."))
        hour, minute = map(int, birth_time.split(":"))
        birth_dt = datetime(year, month, day, hour, minute)
    except ValueError:
        return "❌ Неверный формат даты. Используй ДД.ММ.ГГГГ (например, 26.01.1988)"

    coords = _get_city_coords(birth_place)
    if not coords:
        return f"❌ Город «{birth_place}» не найден в базе. Назови ближайший крупный город или укажи координаты."

    lat, lon = coords
    now = datetime.now()
    age = now.year - year - ((now.month, now.day) < (month, day))

    # Солнце
    sun_lon = _sun_ecliptic_longitude(birth_dt)
    sun_sign, sun_emoji, sun_element, sun_degree = _get_sign_by_degree(sun_lon)

    # Луна
    moon_lon = _moon_ecliptic_longitude(birth_dt)
    moon_sign, moon_emoji, moon_element, moon_degree = _get_sign_by_degree(moon_lon)

    # ASC
    asc_lon = _ascendant_approx(birth_dt, lat, lon)
    asc_sign, asc_emoji, asc_element, asc_degree = _get_sign_by_degree(asc_lon)

    # Фаза Луны при рождении
